import { randomUUID } from "node:crypto";
import { z } from "zod";
export const trackedCategory = (category) =>
  ["Computers", "Mobiles", "Tablets"].includes(category);
export const unitSchema = z.object({
  id: z.string().optional(),
  serial: z.string().trim().max(120).default(""),
  condition: z.enum(["New", "Used", "Refurbished"]).optional(),
  battery: z.string().max(100).default(""),
  notes: z.string().max(1000).default(""),
  accessories: z.string().max(500).default(""),
  price: z.number().int().min(0).max(1e12).optional(),
});
export const unitFields = {
  unit_ids: z.array(z.string().min(1)).max(1000).optional(),
  units: z.array(unitSchema).max(1000).optional(),
};
export function link(s, line, unit, kind) {
  const snapshot = {
    id: unit.id,
    code: unit.code,
    serial: unit.serial || "",
    condition: unit.condition,
    battery: unit.battery,
    notes: unit.notes,
    accessories: unit.accessories,
    price: unit.price,
  };
  s.run(
    "INSERT INTO unit_lines(line_id,unit_id,kind,snapshot) VALUES (?,?,?,?)",
    line.id,
    unit.id,
    kind,
    JSON.stringify(snapshot),
  );
}
function nextCode(s) {
  s.run(
    "INSERT OR IGNORE INTO sequences(name,value) VALUES ('device_units',0)",
  );
  return (
    "TM-" +
    String(
      s.one(
        "UPDATE sequences SET value=value+1 WHERE name='device_units' RETURNING value",
      ).value,
    ).padStart(8, "0")
  );
}
export function receiveUnits(
  s,
  product,
  batch,
  quantity,
  line,
  kind,
  details = [],
  restoreCandidates,
) {
  for (let i = 0; i < quantity; i++) {
    const raw = details[i] || {};
    const d = unitSchema.parse(raw),
      id = randomUUID();
    const restoreIndex = restoreCandidates
      ? d.id
        ? restoreCandidates.findIndex((u) => u.id === d.id)
        : 0
      : -1;
    if (restoreCandidates && d.id && restoreIndex < 0)
      throw new Error("Purchase device changed. Reload the invoice.");
    const restored =
      restoreCandidates && restoreIndex >= 0
        ? restoreCandidates.splice(restoreIndex, 1)[0]
        : undefined;
    const unit = {
      id: restored?.id || id,
      code: restored?.code || nextCode(s),
      serial:
        raw.serial !== undefined ? d.serial || null : restored?.serial || null,
      condition: d.condition || restored?.condition || product.condition,
      battery: raw.battery !== undefined ? d.battery : restored?.battery || "",
      notes: raw.notes !== undefined ? d.notes : restored?.notes || "",
      accessories:
        raw.accessories !== undefined
          ? d.accessories
          : restored?.accessories || "",
      price: d.price ?? restored?.price ?? product.price,
    };
    const previous = d.serial
      ? s.one(
          "SELECT * FROM inventory_units WHERE serial=? COLLATE NOCASE",
          d.serial,
        )
      : null;
    if (
      previous &&
      previous.status === "returned_supplier" &&
      previous.product_id === product.id
    ) {
      unit.id = previous.id;
      unit.code = previous.code;
      s.run(
        "UPDATE inventory_units SET batch_id=?,condition=?,battery=?,notes=?,accessories=?,price=?,status='available',sale_line_id=NULL WHERE id=?",
        batch,
        unit.condition,
        unit.battery,
        unit.notes,
        unit.accessories,
        unit.price,
        unit.id,
      );
    } else
      s.run(
        `INSERT INTO inventory_units(id,code,product_id,batch_id,serial,condition,battery,notes,accessories,price,status) VALUES (?,?,?,?,?,?,?,?,?,?,'available')`,
        unit.id,
        unit.code,
        product.id,
        batch,
        unit.serial,
        unit.condition,
        unit.battery,
        unit.notes,
        unit.accessories,
        unit.price,
      );
    if (line) link(s, line, unit, kind);
  }
}
export function migrateUnits(s) {
  if (s.setting("individualDevicesV1")) return;
  s.transaction(() => {
    s.run(
      "UPDATE products SET serialized=1 WHERE category IN ('Computers','Mobiles','Tablets')",
    );
    // Stream one batch at a time so an existing large catalog is not loaded into memory.
    for (const b of s.db
      .prepare(
        `SELECT b.*,p.condition,p.price FROM batches b JOIN products p ON p.id=b.product_id WHERE p.serialized=1 AND b.remaining>0`,
      )
      .iterate()) {
      // IDs generated by SQLite; no new stock or accounting postings are made.
      s.run(
        `WITH RECURSIVE n(x) AS (SELECT 1 UNION ALL SELECT x+1 FROM n WHERE x<?)
        INSERT INTO inventory_units(id,code,product_id,batch_id,condition,price,status)
        SELECT lower(hex(randomblob(16))),'TM-'||lower(hex(randomblob(16))),?,?,?,?, 'available' FROM n`,
        b.remaining,
        b.product_id,
        b.id,
        b.condition,
        b.price,
      );
    }
    s.saveSetting("individualDevicesV1", true);
  });
}
export function selectUnits(s, product, line, doc) {
  const ids = line.unit_ids || [];
  // New Sale posts quantity only; assign oldest available devices FIFO.
  if (!ids.length && doc.kind === "sale") {
    const units = s.all(
      `SELECT u.*,b.received_at,b.owner_id,b.owner_unit_amount,b.unit_cost
       FROM inventory_units u JOIN batches b ON b.id=u.batch_id
       WHERE u.product_id=? AND u.status='available' AND SUBSTR(b.received_at,1,10)<=?
       ORDER BY b.received_at ASC, b.rowid ASC, u.rowid ASC
       LIMIT ?`,
      product.id,
      doc.date,
      line.quantity,
    );
    if (units.length !== line.quantity)
      throw new Error(
        "Not enough available devices for this quantity. Refresh stock and try again.",
      );
    return units;
  }
  if (ids.length !== line.quantity || new Set(ids).size !== ids.length)
    throw new Error(
      "Select exactly one available device for every unit on this line.",
    );
  const units = ids.map((id) =>
    s.one(
      `SELECT u.*,b.received_at,b.owner_id,b.owner_unit_amount,b.unit_cost FROM inventory_units u JOIN batches b ON b.id=u.batch_id WHERE u.id=?`,
      id,
    ),
  );
  for (const u of units)
    if (
      !u ||
      u.product_id !== product.id ||
      u.status !== "available" ||
      u.received_at.slice(0, 10) > doc.date
    )
      throw new Error(
        "A selected device is unavailable or belongs to another product. Refresh the device list.",
      );
  return units;
}
export function consumeUnits(s, product, line, doc) {
  const units = selectUnits(s, product, line, doc);
  let cost = 0,
    ownerCost = 0;
  for (const u of units) {
    if (u.owner_id && doc.kind !== "sale")
      throw new Error("Return customer-owned devices through Customer resale.");
    const c = u.owner_id ? u.owner_unit_amount : u.unit_cost;
    if (
      s.run(
        "UPDATE batches SET remaining=remaining-1 WHERE id=? AND remaining>0",
        u.batch_id,
      ).changes !== 1
    )
      throw new Error("Selected device stock changed.");
    s.run(
      "INSERT INTO allocations VALUES (?,?,?,?,?,0)",
      randomUUID(),
      line.id,
      u.batch_id,
      1,
      c,
    );
    s.run(
      "UPDATE inventory_units SET status=?,sale_line_id=? WHERE id=?",
      doc.kind === "sale" ? "sold" : "adjusted_out",
      doc.kind === "sale" ? line.id : null,
      u.id,
    );
    link(s, line, u, doc.kind);
    cost += c;
    if (u.owner_id) ownerCost += c;
  }
  s.move(doc, product, -line.quantity, -(cost - ownerCost));
  return cost;
}
export function documentUnits(s, line, kind) {
  return s
    .all(
      `SELECT e.snapshot,u.status,u.sale_line_id,u.batch_id,b.unit_cost,b.line_id purchase_line_id FROM unit_lines e JOIN inventory_units u ON u.id=e.unit_id JOIN batches b ON b.id=u.batch_id WHERE e.line_id=? ORDER BY e.rowid`,
      line.id,
    )
    .map((r) => ({
      ...JSON.parse(r.snapshot),
      status: r.status,
      returnable:
        kind === "sale"
          ? r.status === "sold" && r.sale_line_id === line.id
          : kind === "purchase"
            ? r.status === "available" && r.purchase_line_id === line.id
            : false,
      ...(kind === "purchase" ? { return_cost: r.unit_cost } : {}),
    }));
}
export function returnSelection(s, original, ol, request) {
  if (!ol.units?.length) return null; // Old invoices remain quantity returns with original batch costs.
  const ids = request.unit_ids || [];
  if (ids.length !== request.quantity || new Set(ids).size !== ids.length)
    throw new Error("Select the exact devices being returned.");
  const units = ids.map((id) => {
    const linked = ol.units.find((u) => u.id === id && u.returnable);
    const u = s.one("SELECT * FROM inventory_units WHERE id=?", id);
    if (!linked || !u)
      throw new Error("This device is not returnable on this invoice.");
    return {
      ...u,
      unit_cost: s.one("SELECT unit_cost FROM batches WHERE id=?", u.batch_id)
        .unit_cost,
    };
  });
  return units;
}
export function returnUnits(s, product, original, ol, request, line, doc) {
  const units = returnSelection(s, original, ol, request);
  if (!units) return null;
  let cost = 0,
    ownerCost = 0;
  const owners = new Map();
  for (const u of units) {
    const b = s.one("SELECT * FROM batches WHERE id=?", u.batch_id);
    if (original.kind === "sale") {
      const a = s.one(
        "SELECT * FROM allocations WHERE line_id=? AND batch_id=? AND returned<quantity ORDER BY rowid LIMIT 1",
        ol.id,
        b.id,
      );
      if (!a)
        throw new Error("Original device cost allocation is unavailable.");
      s.run("UPDATE allocations SET returned=returned+1 WHERE id=?", a.id);
      s.run("UPDATE batches SET remaining=remaining+1 WHERE id=?", b.id);
      s.run(
        "UPDATE inventory_units SET status='available',sale_line_id=NULL WHERE id=?",
        u.id,
      );
    } else {
      if (
        s.run(
          "UPDATE batches SET remaining=remaining-1,quantity=quantity-1 WHERE id=? AND remaining>0",
          b.id,
        ).changes !== 1
      )
        throw new Error("Device is no longer available.");
      s.run(
        "UPDATE inventory_units SET status='returned_supplier' WHERE id=?",
        u.id,
      );
    }
    const c = b.owner_id ? b.owner_unit_amount : b.unit_cost;
    cost += c;
    if (b.owner_id) {
      ownerCost += c;
      owners.set(b.owner_id, (owners.get(b.owner_id) || 0) + c);
    }
    link(s, line, u, doc.kind);
  }
  s.move(
    doc,
    product,
    original.kind === "sale" ? request.quantity : -request.quantity,
    original.kind === "sale" ? cost - ownerCost : -cost,
  );
  return { cost, ownerCost, owners };
}
export function unitCommand(s, user, command, args) {
  if (
    !user.permissions.some((p) =>
      ["inventory", "sales", "purchases", "finance"].includes(p),
    )
  )
    throw new Error("Permission required for device inventory.");
  if (command === "unitUpdate") {
    if (!user.permissions.includes("inventory"))
      throw new Error("Permission required: inventory");
    const d = unitSchema.parse(args);
    return s.transaction(() => {
      const u = s.one(
        "SELECT * FROM inventory_units WHERE id=?",
        z.string().parse(args.id),
      );
      if (!u || u.status !== "available")
        throw new Error("Only available devices can be edited.");
      s.run(
        "UPDATE inventory_units SET serial=?,condition=?,battery=?,notes=?,accessories=?,price=? WHERE id=?",
        d.serial || null,
        d.condition || u.condition,
        d.battery,
        d.notes,
        d.accessories,
        d.price ?? u.price,
        u.id,
      );
      s.audit(user, "Update device", u.id, { code: u.code });
      return { id: u.id };
    });
  }
  if (command === "unitLookup") {
    const code = z.string().max(120).parse(args.code);
    const matches = s.all(
      "SELECT * FROM inventory_units WHERE (code=? OR serial=? COLLATE NOCASE) AND status='available' LIMIT 2",
      code,
      code,
    );
    if (!matches.length) throw new Error("Available device not found.");
    if (matches.length !== 1)
      throw new Error(
        "This scan matches more than one device. Choose the exact device from the catalog.",
      );
    const unit = matches[0];
    return {
      unit,
      product: s.listProducts({ id: unit.product_id }, user).rows[0],
    };
  }
  const productId = z.string().parse(args.product_id),
    offset = z
      .number()
      .int()
      .min(0)
      .parse(args.offset || 0),
    q = z
      .string()
      .max(120)
      .parse(args.q || "");
  const edit =
    args.sale_id &&
    s.one("SELECT id FROM documents WHERE id=? AND kind='sale'", args.sale_id);
  const rows = s.all(
    `SELECT u.*,b.unit_cost,b.owner_id,b.owner_unit_amount FROM inventory_units u JOIN batches b ON b.id=u.batch_id WHERE u.product_id=? AND (?='' OR u.batch_id=?) AND ${edit ? "(u.status='available' OR u.sale_line_id IN (SELECT id FROM document_lines WHERE document_id=?))" : "u.status='available'"} AND (u.code LIKE ? OR COALESCE(u.serial,'') LIKE ?) ORDER BY u.rowid LIMIT 51 OFFSET ?`,
    productId,
    args.batch_id || "",
    args.batch_id || "",
    ...(edit ? [args.sale_id] : []),
    `%${q}%`,
    `%${q}%`,
    offset,
  );
  return {
    rows: rows.slice(0, 50).map(({ unit_cost, owner_unit_amount, ...u }) => ({
      ...u,
      ...(user.permissions.includes("view_costs")
        ? { unit_cost, owner_unit_amount }
        : {}),
    })),
    next: rows.length > 50 ? offset + 50 : null,
  };
}
