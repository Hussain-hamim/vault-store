const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const { randomUUID } = require("node:crypto");
function validatePrintJob(job) {
  if (
    !job ||
    !["invoice", "report", "label"].includes(job.kind) ||
    !["print", "pdf"].includes(job.mode)
  )
    throw new Error("Invalid print job.");
  if (
    typeof job.html !== "string" ||
    Buffer.byteLength(job.html) > 8_000_000 ||
    !job.html.startsWith("<!doctype html>")
  )
    throw new Error("Invalid or oversized print document.");
  if (
    typeof job.title !== "string" ||
    !job.title.trim() ||
    job.title.length > 250
  )
    throw new Error("Invalid print title.");
  if (
    !job.options ||
    typeof job.options !== "object" ||
    Array.isArray(job.options)
  )
    throw new Error("Invalid print options.");
  if (job.kind === "invoice") {
    if (
      job.source?.type !== "invoice" ||
      typeof job.source.id !== "string" ||
      !job.source.id ||
      job.source.id.length > 200
    )
      throw new Error("Invalid invoice source.");
  } else if (
    // Reports and QR/product labels both use a permission-gated report source.
    job.source?.type !== "report" ||
    ![
      "reports",
      "finance",
      "inventory",
      "people",
      "sales",
      "purchases",
    ].includes(job.source.permission)
  )
    throw new Error("Invalid report source.");
  return job;
}
/** Isolated output window: no preload, no Node access, no external resources. */
async function withPrintWindow(BrowserWindow, html, parent, callback) {
  const folder = await fs.mkdtemp(path.join(os.tmpdir(), "vault-print-"));
  const file = path.join(folder, "document.html");
  let win;
  try {
    await fs.writeFile(file, html, { mode: 0o600 });
    win = new BrowserWindow({
      show: false,
      parent,
      width: 1100,
      height: 900,
      webPreferences: {
        nodeIntegration: false,
        contextIsolation: true,
        sandbox: true,
        webSecurity: true,
        partition: `vault-print-${randomUUID()}`,
      },
    });
    const allowedFile = pathToFileURL(file).href;
    win.webContents.session.setPermissionRequestHandler(
      (_contents, _permission, respond) => respond(false),
    );
    win.webContents.session.webRequest.onBeforeRequest((details, respond) =>
      respond({
        cancel: details.url !== allowedFile && !details.url.startsWith("data:"),
      }),
    );
    win.webContents.setWindowOpenHandler(() => ({ action: "deny" }));
    win.webContents.on("will-navigate", (event, url) => {
      if (url !== allowedFile) event.preventDefault();
    });
    // Output HTML is generated by the app and its CSP blocks all scripts and external resources.
    await win.loadFile(file);
    await win.webContents.executeJavaScript(
      "Promise.all([document.fonts.ready,...Array.from(document.images).map(i=>i.decode().catch(()=>{}))]).then(()=>true)",
    );
    return await callback(win.webContents);
  } finally {
    if (win && !win.isDestroyed()) win.destroy();
    await fs.rm(folder, { recursive: true, force: true });
  }
}
module.exports = { validatePrintJob, withPrintWindow };
